#!/usr/bin/env python3
"""Check that every MeetStream API operation, guide-only route and docs page has an owning skill.

Reads sources/openapi.json, sources/llms.txt, data/guide-routes.json and coverage.json.
Fails (exit 1) when an item matches no rule or a rule names a skill that does not exist.
Writes docs/coverage.md: owners, plus whether each owning skill's own text (not the generated
references) mentions the item. Those "not mentioned" rows are the work list for Phase 2.

Usage:
  python3 scripts/check_coverage.py           check and write docs/coverage.md
  python3 scripts/check_coverage.py --check   check, and fail if docs/coverage.md is out of date

Python standard library only.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "docs" / "coverage.md"


def load(p: Path):
    return json.loads(p.read_text(encoding="utf-8"))


def skill_text(name: str) -> str:
    """The skill's own text, without the generated references."""
    d = ROOT / "skills" / name
    parts = []
    for p in sorted(d.rglob("*.md")):
        if "generated" in p.parts:
            continue
        parts.append(p.read_text(encoding="utf-8"))
    return "\n".join(parts)


def owner(rules: list, key: str) -> str | None:
    for pattern, skill in rules:
        if re.search(pattern, key):
            return skill
    return None


def mentioned(text: str, needle: str) -> bool:
    return needle in text


def path_needle(path: str) -> str:
    """The most specific readable part of an API path: the last literal segment(s)."""
    segs = [s for s in path.split("/") if s and not s.startswith("{") and s not in ("api", "v1")]
    return "/".join(segs[-2:]) if len(segs) >= 2 and segs[-1] in ("apps", "credentials", "domains") else (segs[-1] if segs else path)


def build_report() -> tuple[str, list[str]]:
    cov = load(ROOT / "coverage.json")
    spec = load(ROOT / "sources" / "openapi.json")
    routes = load(ROOT / "data" / "guide-routes.json")["routes"]
    llms = (ROOT / "sources" / "llms.txt").read_text(encoding="utf-8")
    skills = {p.name for p in (ROOT / "skills").iterdir() if (p / "SKILL.md").is_file()}
    errors: list[str] = []
    for section in ("operations", "guide_routes", "pages"):
        for _, s in cov[section]:
            if s not in skills:
                errors.append(f"coverage.json names a skill that does not exist: {s}")
    texts = {s: skill_text(s) for s in skills}

    ops = [(m.upper(), p, o) for p, item in spec["paths"].items() for m, o in item.items()
           if m in ("get", "post", "put", "patch", "delete")]
    rows_ops, rows_routes, rows_pages = [], [], []
    for m, p, o in ops:
        key = f"{m} {p}"
        s = owner(cov["operations"], key)
        if not s:
            errors.append(f"no owner for operation {key}")
            continue
        rows_ops.append((key, s, mentioned(texts[s], path_needle(p))))
    for r in routes:
        key = f"{r['method']} {r['path']}"
        s = owner(cov["guide_routes"], key)
        if not s:
            errors.append(f"no owner for guide-only route {key}")
            continue
        rows_routes.append((key, s, mentioned(texts[s], path_needle(r["path"]))))
    pages = sorted(set(m.group(1).removesuffix(".md") for m in re.finditer(r"\((https://docs\.meetstream\.ai/[^)]+)\)", llms)))
    for url in pages:
        if "/api-reference/api-endpoints/" in url:
            continue  # one page per operation: covered with the operations above
        s = owner(cov["pages"], url)
        if not s:
            errors.append(f"no owner for docs page {url}")
            continue
        slug = url.rstrip("/").split("/")[-1]
        rows_pages.append((url, s, mentioned(texts[s], slug)))

    def section(title: str, rows: list) -> str:
        miss = sum(1 for r in rows if not r[2])
        out = f"## {title}\n\n{len(rows)} items, {miss} not yet mentioned in the owning skill's own text.\n\n"
        out += "| Item | Owner skill | Mentioned in owner |\n|---|---|---|\n"
        for k, s, ok in rows:
            out += f"| `{k}` | {s} | {'yes' if ok else '**no**'} |\n"
        return out + "\n"

    report = ("<!-- GENERATED by scripts/check_coverage.py. Do not edit. -->\n# Docs coverage\n\n"
              "Every API operation, guide-only route and docs page, with the skill that owns it (coverage.json). "
              "All items always appear in the generated references (`skills/meetstream/references/generated/`). "
              "**no** means the owning skill's own text does not mention it yet: the work list for the Phase 2 restructure.\n\n"
              + section("API operations", rows_ops) + section("Guide-only routes", rows_routes) + section("Docs pages", rows_pages))
    return report, errors


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    report, errors = build_report()
    for e in errors:
        print("ERROR:", e)
    if a.check:
        if not REPORT.is_file() or REPORT.read_text(encoding="utf-8") != report:
            print("docs/coverage.md is out of date. Run: python3 scripts/check_coverage.py")
            errors.append("stale report")
    else:
        REPORT.parent.mkdir(exist_ok=True)
        REPORT.write_text(report, encoding="utf-8")
    if errors:
        return 1
    print("coverage: every operation, guide-only route and docs page has an owner")
    return 0


if __name__ == "__main__":
    sys.exit(main())
