def gen_providers() -> str:
    p = load(DATA / "providers.json")
    keyname = {"none": "no key needed", "dashboard": "your key (dashboard: Integrations > Transcription)"}
    out = header("Transcription providers", "Set one provider in `recording_config.transcript.provider`. Prices: see the pricing page, never quote from memory.", ["llms"])
    out += "## After the call\n\n" + table(["Provider", "Key", "Note"], [[f"`{a}`", keyname[b], c] for a, b, c in p["post_call"]])
    out += "## Live (streaming)\n\nNeeds `live_transcription_required.webhook_url`.\n\n" + table(["Provider", "Key", "Note"], [[f"`{a}`", keyname[b], c] for a, b, c in p["streaming"]])
    out += "## Rules\n\n" + bullets(p["rules"]) + "Sources: " + ", ".join([p["source"]] + p["also"]) + "\n"
    return out


def gen_cli() -> str:
    cat = load(SRC / "cli-commands.json")
    rel = load(SRC / "cli-released.json")
    released = set(rel["paths"])
    wf = load(DATA / "cli-workflows.json")
    skip = wf.get("not_in_skills", {})
    cmds = [c for c in cat["commands"] if not c.get("planned") and c["path"] not in skip]
    known = {c["path"] for c in cat["commands"]}
    pre = sorted(c["path"] for c in cmds if c["path"] not in released)
    out = header("meetstream CLI map",
                 f"The CLI for agent users: workflows with the API calls under them, then every command and flag. "
                 f"Catalog from CLI {cat.get('version')}; released CLI is {rel['version']}. "
                 f"Commands marked **pre-release** are not in {rel['version']} yet: do not tell users they can run them until a release has them.",
                 ["cli", "cli_released"])
    out += toc(["Rules", "Workflows", "Commands"])
    out += ("## Rules\n\n- Always pass `--json --no-input`; parse stdout; human text goes to stderr.\n"
            "- Exit codes: " + ", ".join(f"`{k}` {v}" for k, v in cat.get("exit_codes", {}).items()) + ".\n"
            "- Errors with `--json`: " + cat.get("error_shape", "") + ". Follow the `hint`.\n"
            "- Sign in with `meetstream login` (browser). Never ask for a key in the chat.\n\n")
    out += "## Workflows\n\n" + table(["Workflow", "CLI", "API calls", "Events and results"], wf["rows"])
    out += "## Commands\n\n| Command | What it does | Flags |\n|---|---|---|\n"
    for c in sorted(cmds, key=lambda x: x["path"]):
        flags = []
        for f in c.get("flags") or []:
            s = f"`--{f['name']}`"
            if f.get("enum"):
                s += " (" + "|".join(f["enum"]) + ")"
            flags.append(s)
        tag = " **pre-release**" if c["path"] not in released else ""
        out += f"| `meetstream {c['path']}`{tag} | {cell(c.get('short'))} | {cell(', '.join(flags))} |\n"
    # The skipped commands are named only in data/cli-workflows.json, so old-CLI text checks stay clean.
    out += f"\n{len(cmds)} commands; {len(pre)} pre-release; {len(skip)} key-fallback command(s) left out on purpose (skills never offer a pasted key).\n"
    # Check that the hand-kept workflow table names only real commands.
    missing = []
    prefixes = {" ".join(k.split()[:i]) for k in known for i in range(1, len(k.split()) + 1)}
    for r in wf["rows"]:
        for part in r[1].split(" · "):
            words = []
            for w in part.split():
                if not re.match(r"^[a-z][a-z0-9-]*$", w):
                    break
                words.append(w)
            if words and " ".join(words) not in prefixes:
                missing.append(" ".join(words))
    if missing:
        raise SystemExit(f"data/cli-workflows.json names commands the CLI does not have: {sorted(set(missing))}")
    return out


def gen_mcp() -> str:
    tools = load(SRC / "mcp-tools.json")
    on = [t for t in tools if t["enabled"]]
    out = header("Hosted MCP tools",
                 f"The tools of the hosted MeetStream MCP server (https://mcp.meetstream.ai/mcp, OAuth sign-in): {len(on)} on in production"
                 + (f", {len(tools) - len(on)} off by default" if len(tools) > len(on) else "") + ".",
                 ["mcp"])
    out += "| Tool | What it does | Inputs (required in bold) |\n|---|---|---|\n"
    for t in sorted(tools, key=lambda x: x["name"]):
        ins = ", ".join(f"**{i}**" if i in t["required"] else i for i in t["inputs"])
        note = f" ({t['note']})" if t.get("note") else ""
        out += f"| `{t['name']}` | {cell(first_sentence(t['description'], 240) + note)} | {cell(ins)} |\n"
    return out + "\n"


FILES = {
    "endpoints.md": gen_endpoints,
    "create-bot-fields.md": gen_create_bot,
    "events.md": gen_events,
    "errors.md": gen_errors,
    "providers.md": gen_providers,
    "cli-map.md": gen_cli,
    "mcp-tools.md": gen_mcp,
}


def build() -> dict[str, str]:
    return {name: fn().rstrip("\n") + "\n" for name, fn in FILES.items()}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    files = build()
    if a.check:
        bad = [n for n, text in files.items() if not (OUT / n).is_file() or (OUT / n).read_text(encoding="utf-8") != text]
        extra = sorted(p.name for p in OUT.glob("*.md") if p.name not in files) if OUT.is_dir() else []
        for n in bad:
            print("out of date:", n)
        for n in extra:
            print("not generated (remove it):", n)
        if bad or extra:
            print("Run: python3 scripts/gen_references.py && python3 scripts/build_stores.py")
            return 1
        print("generated references are up to date")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for p in OUT.glob("*.md"):
        if p.name not in files:
            p.unlink()
    for n, text in files.items():
        (OUT / n).write_text(text, encoding="utf-8")
    print("wrote", ", ".join(f"{n} ({t.count(chr(10))} lines)" for n, t in files.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
