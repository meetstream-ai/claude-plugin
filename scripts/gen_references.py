    out += "## Retry rules\n\n" + bullets(e["retry"])
    out += "## Limits\n\n" + table(["What", "Limit"], e["limits"])
    out += "## Idempotency\n\n" + bullets(e["idempotency"])
    out += "## Error bodies\n\n" + bullets(e["error_bodies"])
    out += "Sources: " + ", ".join([e["source"]] + e["also"]) + "\n"
