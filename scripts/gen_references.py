#!/usr/bin/env python3
"""Generate the MeetStream API reference files that every skill relies on.

Inputs (never edit the outputs; edit these):
  sources/openapi.json        the public API spec (scripts/sync_sources.py)
  sources/llms.txt            the docs page list, for one docs link per operation
  sources/cli-commands.json   `meetstream commands --json`
  sources/cli-released.json   command paths of the released CLI (marks pre-release commands)
  sources/mcp-tools.json      the hosted MCP tool list
  sources/lock.json           source versions, written into each file header
  data/*.json                 hand-kept facts from the docs (events, errors, providers, guide-only routes)

Output: skills/meetstream/references/generated/*.md (copied into every store build).

Usage:
  python3 scripts/gen_references.py          write the files
  python3 scripts/gen_references.py --check  exit 1 if the committed files differ (CI)

Python standard library only.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "sources"
DATA = ROOT / "data"
OUT = ROOT / "skills" / "meetstream" / "references" / "generated"
METHODS = ("get", "post", "put", "patch", "delete")
DOCS = "https://docs.meetstream.ai"


def load(p: Path):
    return json.loads(p.read_text(encoding="utf-8"))


SPEC = load(SRC / "openapi.json")
LOCK = load(SRC / "lock.json")
LLMS = (SRC / "llms.txt").read_text(encoding="utf-8")
OVR = load(DATA / "overrides.json")
PAGES = {m.group(1): m.group(2).removesuffix(".md") for m in
         re.finditer(r"- \[([^\]]+)\]\((https://docs\.meetstream\.ai/api-reference/api-endpoints/[^)]+)\)", LLMS)}


def cell(s) -> str:
    """One Markdown table cell: no pipes or newlines."""
    return " ".join(str(s if s is not None else "").replace("|", "\\|").split())


def first_sentence(s: str, limit: int = 220) -> str:
    s = " ".join((s or "").split())
    m = re.match(r"(.+?[.!?])(\s|$)", s)
    s = m.group(1) if m else s
    return s if len(s) <= limit else s[: limit - 1].rstrip() + "…"


def header(title: str, what: str, sources: list[str]) -> str:
    src = LOCK.get("sources", {})
    bits = []
    for k in sources:
        v = src.get(k, {})
        ver = v.get("version") or v.get("count") or ""
        date = ""  # content hash only, so an unchanged source makes no diff
        h = (v.get("sha256") or "")[:8]
        bits.append(" ".join(x for x in [k, f"v{ver}" if ver and k in ("cli", "cli_released", "openapi") else (f"{ver} items" if ver else ""), h, date] if x))
    return (f"<!-- GENERATED by scripts/gen_references.py. Do not edit: change sources/ or data/ and regenerate. -->\n"
            f"# {title}\n\n{what}\n\nSources: {'; '.join(bits)}. Latest docs: {DOCS}/llms.txt (append `.md` to any page).\n\n")


def toc(sections: list[str]) -> str:
    def anchor(t: str) -> str:
        return re.sub(r"[^a-z0-9 -]", "", t.lower()).strip().replace(" ", "-")
    return "## Contents\n\n" + "\n".join(f"- [{s}](#{anchor(s)})" for s in sections) + "\n\n"


def resolve(schema: dict) -> dict:
    seen = 0
    while isinstance(schema, dict) and "$ref" in schema and seen < 20:
        name = schema["$ref"].split("/")[-1]
        schema = SPEC.get("components", {}).get("schemas", {}).get(name, {})
        seen += 1
    return schema or {}


def type_of(s: dict) -> str:
    s = resolve(s)
    if "enum" in s:
        return "enum"
    t = s.get("type")
    if isinstance(t, list):
        t = "/".join(x for x in t if x != "null")
    if t == "array":
        return f"array of {type_of(s.get('items', {}))}"
    if not t and ("oneOf" in s or "anyOf" in s):
        return "one of " + ", ".join(type_of(x) for x in (s.get("oneOf") or s.get("anyOf"))[:4])
    return t or ("object" if s.get("properties") else "any")


def body_fields(op: dict) -> tuple[list[str], list[str]]:
    rb = op.get("requestBody", {}).get("content", {})
    schema = resolve(next(iter(rb.values()), {}).get("schema", {})) if rb else {}
    props = schema.get("properties") or {}
    req = set(schema.get("required") or [])
    return [k for k in props if k in req], [k for k in props if k not in req]


